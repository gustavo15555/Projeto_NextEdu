const textosOriginais = new WeakMap();
const atributosOriginais = new WeakMap();

function aplicarIdiomaNextEdu() {
    const idioma = localStorage.getItem("idioma") || "pt";
    const indice = idioma === "en" ? 0 : idioma === "es" ? 1 : -1;

    document.documentElement.lang = idioma === "en" ? "en" : idioma === "es" ? "es" : "pt-BR";

    const textos = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let no;

    while (no = textos.nextNode()) {
        if (!textosOriginais.has(no)) textosOriginais.set(no, no.nodeValue);
        const original = textosOriginais.get(no);
        const chave = original.trim();
        if (!chave) continue;
        const traducao = indice === -1 ? chave : traducoesNextEdu[chave]?.[indice];
        if (traducao) {
            const inicio = original.match(/^\s*/)[0];
            const fim = original.match(/\s*$/)[0];
            no.nodeValue = inicio + traducao + fim;
        }
    }

    document.querySelectorAll("[placeholder], [title], [aria-label], [alt]").forEach(elemento => {
        ["placeholder", "title", "aria-label", "alt"].forEach(atributo => {
            if (!elemento.hasAttribute(atributo)) return;
            if (!atributosOriginais.has(elemento)) atributosOriginais.set(elemento, {});
            const originais = atributosOriginais.get(elemento);
            if (!(atributo in originais)) originais[atributo] = elemento.getAttribute(atributo);
            const original = originais[atributo];
            const traducao = indice === -1 ? original : traducoesNextEdu[original]?.[indice];
            if (traducao) elemento.setAttribute(atributo, traducao);
        });
    });

    const titulo = document.querySelector("title");
    if (titulo) {
        if (!titulo.dataset.tituloOriginal) titulo.dataset.tituloOriginal = titulo.textContent;
        const original = titulo.dataset.tituloOriginal.trim();
        titulo.textContent = indice === -1 ? original : (traducoesNextEdu[original]?.[indice] || original);
    }

    document.dispatchEvent(new CustomEvent("idiomaNextEduAlterado", { detail: { idioma } }));
}

document.addEventListener("DOMContentLoaded", function() {
    aplicarIdiomaNextEdu();

    const seletorIdioma = document.getElementById("idioma");
    if (seletorIdioma) {
        seletorIdioma.value = localStorage.getItem("idioma") || "pt";
        seletorIdioma.addEventListener("change", function() {
            localStorage.setItem("idioma", seletorIdioma.value);
            aplicarIdiomaNextEdu();
        });
    }
});

window.addEventListener("storage", function(evento) {
    if (evento.key === "idioma") aplicarIdiomaNextEdu();
});